"""SynapseOS Agent Runtime — Multi-step Planning, Tool Execution, and Reflection.

Memory-to-Action Loop:
1. Interpret user request with workspace context.
2. Formulate structured plan (AgentPlan) using NVIDIA Nemotron.
3. Validate tool arguments with Pydantic schemas.
4. Enforce approval gates for consequential actions.
5. Execute authorized tools deterministically.
6. Verify outputs and persist outcomes + reflections to persistent memory.
"""

from __future__ import annotations

import json
import time
import uuid
from typing import Any

import structlog
from pydantic import BaseModel, Field
from sqlalchemy.ext.asyncio import AsyncSession

from app.agents.approval_store import approval_store
from app.agents.tools import TOOL_REGISTRY
from app.core.config import settings
from app.core.exceptions import ForbiddenException, NotFoundException
from app.core.llm import LLMResponse, nebius_client
from app.models.user import User
from app.reflection.engine import ReflectionEngine, ReflectionSummary
from app.services.memory.embedding import embedding_service
from app.services.memory.vector_store import VectorStore

logger = structlog.get_logger("synapseos.agents.runtime")


# ── Schemas ──────────────────────────────────────────────────────────────────


class AgentStep(BaseModel):
    """A discrete step in an agent execution plan."""
    step_number: int
    description: str
    tool_name: str
    tool_args: dict[str, Any] = Field(default_factory=dict)
    requires_approval: bool = False
    status: str = "pending"  # pending, awaiting_approval, completed, failed, skipped
    output: dict[str, Any] | None = None
    error: str | None = None


class AgentPlan(BaseModel):
    """Structured plan generated by NVIDIA Nemotron."""
    goal: str
    reasoning: str
    steps: list[AgentStep]
    confidence_score: float = 0.9


class AgentChatRequest(BaseModel):
    """User instruction for agent execution."""
    message: str = Field(..., min_length=1, max_length=2000)
    workspace_id: uuid.UUID
    project_id: uuid.UUID | None = None
    allow_auto_consequential: bool = False


class AgentChatResponse(BaseModel):
    """Result of agent planning and execution."""
    model_config = {"protected_namespaces": ()}

    session_id: str
    message: str
    plan: AgentPlan
    status: str  # completed, awaiting_approval, failed
    pending_step: AgentStep | None = None
    executed_steps: list[AgentStep] = Field(default_factory=list)
    reflection: ReflectionSummary | None = None
    model_used: str
    latency_ms: float
    is_simulated: bool = False
    is_fallback: bool = False
    provider: str = "nebius-token-factory"
    request_id: str | None = None


class AgentApprovalRequest(BaseModel):
    """User approval or rejection for a consequential action."""
    session_id: str
    approved: bool
    workspace_id: uuid.UUID


# ── Pending Execution State Store ─────────────────────────────────────────────

# In-memory store for execution sessions paused waiting for user approval
PENDING_SESSIONS: dict[str, dict[str, Any]] = {}


# ── Agent Runtime Engine ──────────────────────────────────────────────────────


class AgentRuntime:
    """Executes the complete SynapseOS Memory-to-Action loop."""

    def __init__(self, session: AsyncSession):
        self.session = session
        self.reflection_engine = ReflectionEngine(session)
        self.vector_store = VectorStore()

    async def run(
        self,
        req: AgentChatRequest,
        user: User,
    ) -> AgentChatResponse:
        """Interpret request, construct plan, execute safe tools, or pause for approval."""
        start_time = time.perf_counter()
        session_id = str(uuid.uuid4())

        # 1. Retrieve relevant memory context from workspace
        context_snippets = await self._retrieve_context(req.message, req.workspace_id)

        # 2. Generate structured plan using NVIDIA Nemotron
        plan, plan_resp = await self._generate_plan(req.message, context_snippets)

        model_used = plan_resp.model if plan_resp else (f"{settings.nebius_model}-fallback" if nebius_client.is_configured else f"{settings.nebius_model}-simulated")
        is_simulated = plan_resp.is_simulated if plan_resp else True
        is_fallback = plan_resp.is_fallback if plan_resp else bool(nebius_client.is_configured)
        provider = (
            plan_resp.provider
            if plan_resp
            else ("nebius-token-factory (fallback)" if nebius_client.is_configured else "nebius-token-factory (simulated)")
        )
        req_id = plan_resp.request_id if plan_resp else None

        # 3. Check for consequential steps requiring approval
        has_approval_gate = any(s.requires_approval for s in plan.steps)

        if has_approval_gate and not req.allow_auto_consequential:
            # Find first consequential step
            pending_step = next(s for s in plan.steps if s.requires_approval)
            pending_step.status = "awaiting_approval"

            # Store pending state durably
            await approval_store.save_session(
                session_id=session_id,
                user_id=str(user.id),
                workspace_id=str(req.workspace_id),
                project_id=str(req.project_id) if req.project_id else None,
                goal=plan.goal,
                plan=plan.model_dump(),
                step_index=plan.steps.index(pending_step),
            )
            PENDING_SESSIONS[session_id] = {
                "user_id": str(user.id),
                "workspace_id": str(req.workspace_id),
                "project_id": str(req.project_id) if req.project_id else None,
                "goal": plan.goal,
                "plan": plan.model_dump(),
                "step_index": plan.steps.index(pending_step),
            }

            elapsed_ms = (time.perf_counter() - start_time) * 1000
            return AgentChatResponse(
                session_id=session_id,
                message=(
                    f"I have created a plan to achieve: '{plan.goal}'. "
                    f"Step {pending_step.step_number} ('{pending_step.description}') "
                    f"is a consequential action requiring your approval before execution."
                ),
                plan=plan,
                status="awaiting_approval",
                pending_step=pending_step,
                executed_steps=[],
                reflection=None,
                model_used=model_used,
                latency_ms=round(elapsed_ms, 2),
                is_simulated=is_simulated,
                is_fallback=is_fallback,
                provider=provider,
                request_id=req_id,
            )

        # 4. Execute all authorized tools sequentially
        executed_steps, reflection = await self._execute_plan_steps(
            plan=plan,
            user=user,
            workspace_id=req.workspace_id,
            project_id=req.project_id,
        )

        elapsed_ms = (time.perf_counter() - start_time) * 1000
        summary_msg = (
            f"Successfully executed plan for '{plan.goal}'. "
            f"Completed {len(executed_steps)} actions and recorded reflections to memory."
        )

        return AgentChatResponse(
            session_id=session_id,
            message=summary_msg,
            plan=plan,
            status="completed",
            pending_step=None,
            executed_steps=executed_steps,
            reflection=reflection,
            model_used=model_used,
            latency_ms=round(elapsed_ms, 2),
            is_simulated=is_simulated,
            is_fallback=is_fallback,
            provider=provider,
            request_id=req_id,
        )

    async def handle_approval(
        self,
        req: AgentApprovalRequest,
        user: User,
    ) -> AgentChatResponse:
        """Handle user approval or rejection of a pending consequential action."""
        start_time = time.perf_counter()
        
        # Durable approval store validates authorization, TTL, and replay protection
        session_data = await approval_store.consume_session(
            session_id=req.session_id,
            user_id=str(user.id),
            workspace_id=str(req.workspace_id),
            approved=req.approved,
        )
        PENDING_SESSIONS.pop(req.session_id, None)

        plan = AgentPlan.model_validate(session_data["plan"])
        step_idx = session_data["step_index"]
        step = plan.steps[step_idx]

        if not req.approved:
            # User rejected the consequential action
            step.status = "skipped"
            step.output = {"message": "User declined execution of this action."}

            elapsed_ms = (time.perf_counter() - start_time) * 1000
            return AgentChatResponse(
                session_id=req.session_id,
                message=f"Action '{step.description}' was cancelled as requested.",
                plan=plan,
                status="completed",
                pending_step=None,
                executed_steps=[step],
                reflection=None,
                model_used=settings.nebius_model if nebius_client.is_configured else f"{settings.nebius_model}-simulated",
                latency_ms=round(elapsed_ms, 2),
                is_simulated=not nebius_client.is_configured,
                is_fallback=False,
                provider="nebius-token-factory" if nebius_client.is_configured else "nebius-token-factory (simulated)",
            )

        # User approved: execute approved step and remaining steps
        ctx = {
            "session": self.session,
            "user": user,
            "workspace_id": req.workspace_id,
        }

        # Execute approved step
        tool = TOOL_REGISTRY.get(step.tool_name)
        if tool:
            try:
                val_args = tool.validate_args(step.tool_args).model_dump()
                out = await tool.run(val_args, ctx)
                step.status = "completed"
                step.output = out
            except Exception as e:
                step.status = "failed"
                step.error = str(e)

        # Continue with remaining steps if any
        remaining_steps = plan.steps[step_idx + 1 :]
        for r_step in remaining_steps:
            r_tool = TOOL_REGISTRY.get(r_step.tool_name)
            if r_tool:
                try:
                    val_args = r_tool.validate_args(r_step.tool_args).model_dump()
                    out = await r_tool.run(val_args, ctx)
                    r_step.status = "completed"
                    r_step.output = out
                except Exception as e:
                    r_step.status = "failed"
                    r_step.error = str(e)

        # Reflection
        all_executed = [s.model_dump() for s in plan.steps]
        reflection = await self.reflection_engine.reflect_and_learn(
            user=user,
            workspace_id=req.workspace_id,
            goal=plan.goal,
            executed_steps=all_executed,
        )

        elapsed_ms = (time.perf_counter() - start_time) * 1000
        return AgentChatResponse(
            session_id=req.session_id,
            message=f"Approved action '{step.description}' executed successfully.",
            plan=plan,
            status="completed",
            pending_step=None,
            executed_steps=plan.steps,
            reflection=reflection,
            model_used=settings.nebius_model if nebius_client.is_configured else f"{settings.nebius_model}-simulated",
            latency_ms=round(elapsed_ms, 2),
            is_simulated=not nebius_client.is_configured,
            is_fallback=False,
            provider="nebius-token-factory" if nebius_client.is_configured else "nebius-token-factory (simulated)",
        )

    async def _execute_plan_steps(
        self,
        plan: AgentPlan,
        user: User,
        workspace_id: uuid.UUID,
        project_id: uuid.UUID | None,
    ) -> tuple[list[AgentStep], ReflectionSummary]:
        """Execute all steps in an approved plan."""
        ctx = {
            "session": self.session,
            "user": user,
            "workspace_id": workspace_id,
            "project_id": project_id,
        }

        executed: list[AgentStep] = []
        for step in plan.steps:
            tool = TOOL_REGISTRY.get(step.tool_name)
            if not tool:
                step.status = "failed"
                step.error = f"Unregistered tool: '{step.tool_name}'"
                executed.append(step)
                continue

            try:
                validated_args = tool.validate_args(step.tool_args).model_dump()
                out = await tool.run(validated_args, ctx)
                step.status = "completed"
                step.output = out
            except Exception as e:
                logger.error("Step execution failed", step=step.step_number, error=str(e))
                step.status = "failed"
                step.error = str(e)

            executed.append(step)

        # Reflect on outcome and save learned memory
        reflection = await self.reflection_engine.reflect_and_learn(
            user=user,
            workspace_id=workspace_id,
            goal=plan.goal,
            executed_steps=[s.model_dump() for s in executed],
            project_id=project_id,
        )

        return executed, reflection

    async def _retrieve_context(self, message: str, workspace_id: uuid.UUID) -> str:
        """Fetch memory snippets related to the user's message."""
        try:
            emb = await embedding_service.generate_embedding(message)
            hits = await self.vector_store.search(
                embedding=emb,
                top_k=3,
                filters={"workspace_id": str(workspace_id)},
            )
            snippets = []
            for h in hits:
                content = h.get("payload", {}).get("content", "")
                if content:
                    snippets.append(content[:150])
            return "\n".join(snippets)
        except Exception:
            return ""

    async def _generate_plan(self, message: str, context: str) -> tuple[AgentPlan, LLMResponse | None]:
        """Prompt NVIDIA Nemotron to generate a structured AgentPlan."""
        tool_catalog = [
            f"- {tool.name}: {tool.description} (Requires approval: {tool.is_consequential})"
            for tool in TOOL_REGISTRY.values()
        ]
        tool_catalog_text = "\n".join(tool_catalog)

        system_prompt = (
            "You are the SynapseOS Agent Planner powered by NVIDIA Nemotron. "
            "You create structured, safe execution plans that operate within the user's workspace.\n\n"
            "Available tools:\n"
            f"{tool_catalog_text}\n\n"
            "Rules:\n"
            "1. Only use tools from the available tools list.\n"
            "2. If creating a project, you MUST set requires_approval=True.\n"
            "3. If storing key facts or completing tasks, use 'create_memory'.\n"
            "4. Keep plans focused, between 1 and 3 deterministic steps.\n"
            "5. You must output a valid AgentPlan JSON structure."
        )

        user_content = f"Instruction: {message}\n"
        if context:
            user_content += f"Workspace Context:\n{context}\n"

        messages = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_content},
        ]

        try:
            plan, llm_resp = await nebius_client.structured_completion(
                messages=messages,
                response_model=AgentPlan,
            )
            # Re-verify requires_approval against actual TOOL_REGISTRY
            for s in plan.steps:
                tool = TOOL_REGISTRY.get(s.tool_name)
                if tool and tool.is_consequential:
                    s.requires_approval = True
            return plan, llm_resp
        except Exception as e:
            logger.warning("Agent plan generation via LLM failed, using deterministic fallback", error=str(e))
            # Deterministic fallback plan
            is_project_req = "project" in message.lower() and ("create" in message.lower() or "new" in message.lower())

            if is_project_req:
                fallback = AgentPlan(
                    goal=f"Create new project based on request: {message[:60]}",
                    reasoning="The user requested project creation which requires workspace authorization.",
                    steps=[
                        AgentStep(
                            step_number=1,
                            description=f"Create project '{message[:30]}'",
                            tool_name="create_project",
                            tool_args={"name": message[:40].replace("Create project", "").strip() or "New Project"},
                            requires_approval=True,
                        ),
                    ],
                    confidence_score=0.95,
                )
                return fallback, None

            fallback = AgentPlan(
                goal=f"Address request: {message[:60]}",
                reasoning="Process information and record action in workspace memory.",
                steps=[
                    AgentStep(
                        step_number=1,
                        description="Record task outcome in workspace memory",
                        tool_name="create_memory",
                        tool_args={
                            "title": f"Task: {message[:50]}",
                            "content": f"Executed user instruction: {message}",
                            "memory_type": "task",
                        },
                        requires_approval=False,
                    )
                ],
                confidence_score=0.9,
            )
            return fallback, None

